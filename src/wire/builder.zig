test "compression matches exact bytes and reuses rdata names" {
    var buf: [512]u8 = undefined;
    var b = Builder.init(&buf, .{});
    const a = try Name.parse("Host.Local");
    const c = try Name.parse("svc._x._tcp.Local");
    try b.addRR(.answer, c, .ptr, message.class_in, false, 1, .{ .ptr = a });
    const after_first = b.payloadLen();
    // "Host.Local" now exists inside the PTR rdata; the owner of the next
    // record is a pointer only.
    try b.addRR(.answer, try Name.parse("Host.Local"), .a, message.class_in, false, 1, .{ .a = .{ 1, 2, 3, 4 } });
    try testing.expectEqual(after_first + 2 + 10 + 4, b.payloadLen());
    // A case variant is a different byte string: written in full, never
    // through a pointer to the other spelling, so what a peer decodes is
    // exactly what the caller passed (RFC 6762 section 8.2 compares the
    // uncompressed rdata octet by octet).
    const variant = try Name.parse("host.LOCAL");
    try b.addRR(.answer, variant, .a, message.class_in, false, 1, .{ .a = .{ 1, 2, 3, 5 } });
    try testing.expectEqual(after_first + (2 + 10 + 4) + (variant.len + 10 + 4), b.payloadLen());
    const pkt = b.finish();
    const m = try Message.parse(pkt);
    var an = m.answers();
    const r1 = an.next().?;
    // "Local" was compressed against the owner's "Local".
    try expectName("Host.Local", try rdata_mod.decodePtr(pkt, r1));
    const r2 = an.next().?;
    try expectName("Host.Local", r2.name);
    try testing.expectEqualSlices(u8, a.slice(), r2.name.slice());
    const r3 = an.next().?;
    try testing.expectEqualSlices(u8, variant.slice(), r3.name.slice());
    // The rdata name of the PTR shares the "Local" suffix with its owner.
    try testing.expect(r1.rdata.len < a.len);

    // The reviewer's case: owner "x.A" then a PTR to "a". The canonical
    // rdata must be the bytes given, not "A" through a pointer.
    var d = Builder.init(&buf, .{});
    const target = try Name.parse("a");
    try d.addRR(.answer, try Name.parse("x.A"), .ptr, message.class_in, false, 1, .{ .ptr = target });
    const pkt2 = d.finish();
    const m2 = try Message.parse(pkt2);
    var an2 = m2.answers();
    var canon: [64]u8 = undefined;
    try testing.expectEqualSlices(u8, target.slice(), try rdata_mod.canonicalRdata(pkt2, an2.next().?, &canon));
    // Same for an SRV target that differs only in case from the owner's
    // suffix: the decompressed rdata equals the flat encoding.
    var e = Builder.init(&buf, .{});
    const host = try Name.parse("Host.LOCAL");
    const srv: Srv = .{ .port = 1, .target = host };
    try e.addRR(.answer, try Name.parse("Alice._x._tcp.local"), .srv, message.class_in, false, 1, .{ .srv = srv });
    const pkt3 = e.finish();
    const m3 = try Message.parse(pkt3);
    var an3 = m3.answers();
    var flat: [300]u8 = undefined;
    const fl = try rdata_mod.encodeSrv(srv, &flat);
    try testing.expectEqualSlices(u8, flat[0..fl], try rdata_mod.canonicalRdata(pkt3, an3.next().?, &canon));
}

