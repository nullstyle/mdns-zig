//! Packet builder over a caller-owned buffer.
//!
//! Size rules (RFC 6762 section 17, plan section 4.5): the DNS payload has
//! a soft target of 1472 octets over IPv4 and 1452 over IPv6 (one Ethernet
//! frame), and a hard cap of 8972 / 8952 (the 9000-octet limit includes
//! the IP and UDP headers). One record may exceed the soft target up to the
//! hard cap when it is the first record in the packet; a later record that
//! does not fit under the soft target returns `error.NoSpace` and the
//! builder is left unchanged, so the caller can `finish` and start the next
//! packet.
//!
//! Compression (RFC 1035 section 4.1.4) is applied to owner names and to
//! the names inside PTR, SRV and NSEC rdata, which RFC 6762 section 18.14
//! allows. A pointer is only ever written to a prior occurrence with the
//! same bytes (ASCII case included), so the uncompressed rdata a peer
//! reconstructs is byte-for-byte the `Name` the caller passed in. RFC 6762
//! section 8.2 compares "raw uncompressed rdata" octet by octet, and this
//! rule lets the responder compare its local record values against a
//! peer's packet without first parsing back its own probe. (mDNSResponder
//! matches suffixes case-insensitively; the loss in compression when a
//! caller mixes case is a few octets, and the decoder still accepts such
//! pointers from peers.)
//!
//! In `legacy` mode (a unicast reply to a legacy query, RFC 6762 section
//! 6.7, "a conventional unicast response as would be generated by a
//! conventional Unicast DNS server") the SRV target is never compressed
//! (section 18.14), the NSEC next-domain name is never compressed (RFC
//! 4034 section 4.1.1), TTLs are capped at 10 s and the cache-flush bit is
//! cleared.
const std = @import("std");
const name_mod = @import("name.zig");
const message = @import("message.zig");
const rdata_mod = @import("rdata.zig");
const txt_mod = @import("txt.zig");

pub const Name = name_mod.Name;
pub const Header = message.Header;
pub const RType = message.RType;
pub const Section = message.Section;
pub const Srv = rdata_mod.Srv;
pub const Nsec = rdata_mod.Nsec;
pub const Hinfo = rdata_mod.Hinfo;

pub const Family = enum(u8) { v4, v6 };

/// Soft payload target: 1500 - 20 (IPv4) - 8 (UDP).
pub const soft_limit_v4 = 1472;
/// Soft payload target: 1500 - 40 (IPv6) - 8 (UDP).
pub const soft_limit_v6 = 1452;
/// Hard payload cap: 9000 - 20 - 8 (RFC 6762 section 17).
pub const hard_limit_v4 = 8972;
/// Hard payload cap: 9000 - 40 - 8 (RFC 6762 section 17).
pub const hard_limit_v6 = 8952;
/// RFC 6762 section 6.7: TTLs in a legacy unicast response.
pub const legacy_ttl_cap_s: u32 = 10;
/// Compression table size. When full, later names are written without
/// compression; nothing fails.
pub const max_compression_entries = 128;
/// A compression pointer holds a 14-bit offset.
const max_pointer_offset = 0x3FFF;

pub fn softLimit(f: Family) usize {
    return switch (f) {
        .v4 => soft_limit_v4,
        .v6 => soft_limit_v6,
    };
}

pub fn hardLimit(f: Family) usize {
    return switch (f) {
        .v4 => hard_limit_v4,
        .v6 => hard_limit_v6,
    };
}

pub const Options = struct {
    family: Family = .v4,
    /// RFC 6762 section 6.7 unicast reply to a legacy query.
    legacy: bool = false,
    /// Override the per-family soft target (tests, or a known path MTU).
    soft_limit: ?usize = null,
    /// Lower the per-family hard cap. Never raised above the buffer or
    /// above the RFC 6762 section 17 cap for the family (8972 / 8952).
    hard_limit: ?usize = null,
};

/// Record data for `addRR`. Name-bearing variants are compressed against
/// the packet; `raw` is copied as given.
pub const Rdata = union(enum) {
    raw: []const u8,
    a: [4]u8,
    aaaa: [16]u8,
    ptr: Name,
    srv: Srv,
    /// Wire TXT rdata, e.g. `Txt.slice()`. Must be a valid sequence of
    /// length-prefixed strings (`error.InvalidTxt` otherwise); an empty
    /// slice is written as the single zero octet RFC 6763 section 6.1
    /// requires ("DNS-SD implementations MUST NOT emit empty TXT
    /// records"). The 400-octet bound of plan section 4.5 is enforced by
    /// `Txt`, not here, so captured records of any size can be re-emitted.
    txt: []const u8,
    nsec: Nsec,
    hinfo: Hinfo,
};

pub const Error = error{
    /// The item does not fit under the applicable limit. The builder is
    /// unchanged.
    NoSpace,
    /// A question after a record, or a record in a section that precedes
    /// one already written. The builder is unchanged.
    SectionOrder,
    /// An HINFO string over 255 octets.
    StringTooLong,
    /// `Rdata.txt` bytes are not a sequence of length-prefixed strings.
    InvalidTxt,
};

pub const Builder = struct {
    buf: []u8,
    len: usize,
    soft_limit: usize,
    hard_limit: usize,
    legacy: bool,
    header: Header,
    /// Highest section that holds a record, or null while only questions
    /// have been written.
    last_section: ?Section,
    rr_count: usize,
    comp: [max_compression_entries]u16,
    comp_len: usize,

    /// `buf` must hold at least a header (12 octets); that is a caller
    /// contract, not a packet condition, hence the assert.
    pub fn init(buf: []u8, opts: Options) Builder {
        std.debug.assert(buf.len >= Header.len);
        // An override can only lower the cap: RFC 6762 section 17 bounds
        // the whole datagram at 9000 octets including IP and UDP headers.
        const hard = @min(@min(opts.hard_limit orelse hardLimit(opts.family), hardLimit(opts.family)), buf.len);
        const soft = @min(opts.soft_limit orelse softLimit(opts.family), hard);
        return .{
            .buf = buf,
            .len = Header.len,
            .soft_limit = soft,
            .hard_limit = hard,
            .legacy = opts.legacy,
            .header = .{},
            .last_section = null,
            .rr_count = 0,
            .comp = undefined,
            .comp_len = 0,
        };
    }

    /// Start a new packet in the same buffer. Keeps the id and flags.
    pub fn reset(b: *Builder) void {
        b.len = Header.len;
        b.header.qdcount = 0;
        b.header.ancount = 0;
        b.header.nscount = 0;
        b.header.arcount = 0;
        b.last_section = null;
        b.rr_count = 0;
        b.comp_len = 0;
    }

    pub fn setId(b: *Builder, id: u16) void {
        b.header.id = id;
    }

    pub fn setFlags(b: *Builder, flags: Header.Flags) void {
        b.header.flags = flags;
    }

    /// QR=1, AA=1 (RFC 6762 section 18.2, 18.4).
    pub fn setResponse(b: *Builder) void {
        b.header.flags.qr = true;
        b.header.flags.aa = true;
    }

    /// TC bit (RFC 6762 section 18.5): more known answers follow.
    pub fn setTruncated(b: *Builder, tc: bool) void {
        b.header.flags.tc = tc;
    }

    /// Payload length so far, header included.
    pub fn payloadLen(b: *const Builder) usize {
        return b.len;
    }

    pub fn recordCount(b: *const Builder) usize {
        return b.rr_count;
    }

    pub fn questionCount(b: *const Builder) usize {
        return b.header.qdcount;
    }

    /// True when nothing but the header has been written.
    pub fn isEmpty(b: *const Builder) bool {
        return b.len == Header.len;
    }

    /// Write the header and return the packet. The builder stays usable.
    pub fn finish(b: *Builder) []const u8 {
        b.header.write(b.buf[0..Header.len]);
        return b.buf[0..b.len];
    }

    pub fn addQuestion(b: *Builder, name: Name, qtype: RType, qclass: u16, qu: bool) Error!void {
        if (b.last_section != null) return error.SectionOrder;
        if (b.header.qdcount == std.math.maxInt(u16)) return error.NoSpace;
        const saved = b.save();
        errdefer b.restore(saved);
        // Questions always fit under the soft target.
        try b.writeName(name, true, b.soft_limit);
        try b.writeInt(u16, qtype.toInt(), b.soft_limit);
        const class_wire = (qclass & ~message.qu_bit) | (if (qu) message.qu_bit else 0);
        try b.writeInt(u16, class_wire, b.soft_limit);
        b.header.qdcount += 1;
    }

    /// Append a record. Sections must be written in order (answer,
    /// authority, additional). See the module doc for the size rules.
    pub fn addRR(
        b: *Builder,
        section: Section,
        name: Name,
        rtype: RType,
        class: u16,
        cache_flush: bool,
        ttl: u32,
        rdata: Rdata,
    ) Error!void {
        if (b.last_section) |last| {
            if (@backingInt(section) < @backingInt(last)) return error.SectionOrder;
        }
        if (b.header.count(section) == std.math.maxInt(u16)) return error.NoSpace;
        const limit = if (b.rr_count == 0) b.hard_limit else b.soft_limit;
        const saved = b.save();
        errdefer b.restore(saved);

        try b.writeName(name, true, limit);
        try b.writeInt(u16, rtype.toInt(), limit);
        const flush = cache_flush and !b.legacy;
        const class_wire = (class & ~message.cache_flush_bit) | (if (flush) message.cache_flush_bit else 0);
        try b.writeInt(u16, class_wire, limit);
        const ttl_wire = if (b.legacy) @min(ttl, legacy_ttl_cap_s) else ttl;
        try b.writeInt(u32, ttl_wire, limit);
        const rdlength_at = b.len;
        try b.writeInt(u16, 0, limit);
        const rdata_start = b.len;
        switch (rdata) {
            .raw => |bytes| try b.writeBytes(bytes, limit),
            .a => |addr| try b.writeBytes(&addr, limit),
            .aaaa => |addr| try b.writeBytes(&addr, limit),
            .ptr => |target| try b.writeName(target, true, limit),
            .srv => |srv| {
                try b.writeInt(u16, srv.priority, limit);
                try b.writeInt(u16, srv.weight, limit);
                try b.writeInt(u16, srv.port, limit);
                // RFC 6762 section 18.14: never compress the SRV target in
                // a legacy unicast response.
                try b.writeName(srv.target, !b.legacy, limit);
            },
            .txt => |bytes| {
                (txt_mod.View{ .bytes = bytes }).validate() catch return error.InvalidTxt;
                // RFC 6763 section 6.1: an empty TXT is one zero octet.
                try b.writeBytes(if (bytes.len == 0) &.{0} else bytes, limit);
            },
            .nsec => |nsec| {
                // RFC 4034 section 4.1.1: "A sender MUST NOT use DNS name
                // compression on the Next Domain Name field"; RFC 6762
                // section 6.7 makes a legacy reply a conventional unicast
                // response, so that rule applies there. Multicast replies
                // may compress it (RFC 6762 section 18.14).
                try b.writeName(nsec.next, !b.legacy, limit);
                const wb = nsec.wireBitmap();
                if (wb.len != 0) {
                    try b.writeBytes(&.{ 0, @intCast(wb.len) }, limit);
                    try b.writeBytes(wb.buf[0..wb.len], limit);
                }
            },
            .hinfo => |h| {
                if (h.cpu.len > 255 or h.os.len > 255) return error.StringTooLong;
                try b.writeBytes(&.{@intCast(h.cpu.len)}, limit);
                try b.writeBytes(h.cpu, limit);
                try b.writeBytes(&.{@intCast(h.os.len)}, limit);
                try b.writeBytes(h.os, limit);
            },
        }
        const rdlength = b.len - rdata_start;
        if (rdlength > std.math.maxInt(u16)) return error.NoSpace;
        std.mem.writeInt(u16, b.buf[rdlength_at..][0..2], @intCast(rdlength), .big);

        switch (section) {
            .answer => b.header.ancount += 1,
            .authority => b.header.nscount += 1,
            .additional => b.header.arcount += 1,
        }
        b.last_section = section;
        b.rr_count += 1;
    }

    // -- internals ---------------------------------------------------------

    const Saved = struct { len: usize, comp_len: usize };

    fn save(b: *const Builder) Saved {
        return .{ .len = b.len, .comp_len = b.comp_len };
    }

    fn restore(b: *Builder, s: Saved) void {
        b.len = s.len;
        b.comp_len = s.comp_len;
    }

    fn writeBytes(b: *Builder, bytes: []const u8, limit: usize) error{NoSpace}!void {
        if (b.len + bytes.len > limit) return error.NoSpace;
        @memcpy(b.buf[b.len..][0..bytes.len], bytes);
        b.len += bytes.len;
    }

    fn writeInt(b: *Builder, comptime T: type, v: T, limit: usize) error{NoSpace}!void {
        const n = @divExact(@typeInfo(T).int.bits, 8);
        if (b.len + n > limit) return error.NoSpace;
        std.mem.writeInt(T, b.buf[b.len..][0..n], v, .big);
        b.len += n;
    }

    /// Write `name`, replacing the longest suffix already in the packet by
    /// a pointer when `compress` is set. Every label written in full is
    /// added to the compression table, whatever `compress` says.
    fn writeName(b: *Builder, name: Name, compress: bool, limit: usize) error{NoSpace}!void {
        var it = name.labels();
        // Walk suffixes from the whole name down to the last label.
        while (true) {
            const suffix_start = it.pos;
            if (suffix_start >= name.len - 1) break; // only the root remains
            if (compress) {
                if (b.findSuffix(name.buf[suffix_start..name.len])) |target| {
                    const ptr: u16 = 0xC000 | target;
                    try b.writeInt(u16, ptr, limit);
                    return;
                }
            }
            const label = it.next() orelse break;
            b.addCompressionEntry(b.len);
            try b.writeBytes(&.{@intCast(label.len)}, limit);
            try b.writeBytes(label, limit);
        }
        try b.writeBytes(&.{0}, limit);
    }

    /// Offset of a name already in the packet whose uncompressed bytes
    /// equal the wire-form `suffix` exactly, or null. Exact, not case
    /// folded: see the module doc (RFC 6762 section 8.2 compares the
    /// uncompressed rdata octet by octet, so the bytes a peer reconstructs
    /// must be the bytes the caller passed in).
    fn findSuffix(b: *const Builder, suffix: []const u8) ?u16 {
        const written = b.buf[0..b.len];
        for (b.comp[0..b.comp_len]) |off| {
            const d = Name.decode(written, off) catch continue;
            if (std.mem.eql(u8, d.name.slice(), suffix)) return off;
        }
        return null;
    }

    fn addCompressionEntry(b: *Builder, off: usize) void {
        if (b.comp_len >= max_compression_entries) return;
        if (off > max_pointer_offset) return;
        b.comp[b.comp_len] = @intCast(off);
        b.comp_len += 1;
    }
};

