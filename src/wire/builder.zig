test "build -> parse round trip with compression" {
    var buf: [1500]u8 = undefined;
    var b = Builder.init(&buf, .{});
    b.setResponse();
    b.setId(0);
    const svc = try Name.parse("_qmsg._udp.local");
    const inst = try Name.parse("Alice._qmsg._udp.local");
    const host = try Name.parse("studio-a.local");
    const txt = try txt_mod.Txt.build(&.{ .{ .key = "v", .value = "1" }, .{ .key = "flag" } });
    var v6: [16]u8 = @splat(0);
    v6[0] = 0xfe;
    v6[15] = 1;
    try b.addRR(.answer, svc, .ptr, message.class_in, false, 4500, .{ .ptr = inst });
    try b.addRR(.answer, inst, .srv, message.class_in, true, 120, .{ .srv = .{ .port = 4433, .target = host } });
    try b.addRR(.answer, inst, .txt, message.class_in, true, 4500, .{ .txt = txt.slice() });
    try b.addRR(.additional, host, .a, message.class_in, true, 120, .{ .a = .{ 10, 0, 0, 1 } });
    try b.addRR(.additional, host, .aaaa, message.class_in, true, 120, .{ .aaaa = v6 });
    try b.addRR(.additional, host, .nsec, message.class_in, true, 120, .{ .nsec = try Nsec.fromTypes(host, &.{ .a, .aaaa }) });
    try b.addRR(.additional, host, .hinfo, message.class_in, false, 120, .{ .hinfo = .{ .cpu = "arm", .os = "macOS" } });
    const pkt = b.finish();

    // Compression made it smaller than the flat sum of the names.
    const flat = 12 + (svc.len + 10 + inst.len) + (inst.len + 10 + 6 + host.len) + (inst.len + 10 + txt.slice().len) +
        (host.len + 10 + 4) + (host.len + 10 + 16) + (host.len + 10 + host.len + 4) + (host.len + 10 + 10);
    try testing.expect(pkt.len < flat);

    const m = try Message.parse(pkt);
    try testing.expect(m.header.flags.qr and m.header.flags.aa and !m.header.flags.tc);
    try testing.expectEqual(@as(u16, 3), m.header.ancount);
    try testing.expectEqual(@as(u16, 4), m.header.arcount);
    try testing.expectEqual(pkt.len, m.end);
    var an = m.answers();
    const r_ptr = an.next().?;
    try testing.expect(r_ptr.name.eql(&svc));
    try testing.expect(!r_ptr.cache_flush);
    try testing.expectEqual(@as(u32, 4500), r_ptr.ttl);
    try expectName("Alice._qmsg._udp.local", try rdata_mod.decodePtr(pkt, r_ptr));
    const r_srv = an.next().?;
    try testing.expect(r_srv.cache_flush);
    const srv = try rdata_mod.decodeSrv(pkt, r_srv);
    try testing.expectEqual(@as(u16, 4433), srv.port);
    try testing.expect(srv.target.eql(&host));
    // The SRV target was compressed (rdata is shorter than the flat form).
    try testing.expect(r_srv.rdata.len < 6 + host.len);
    const r_txt = an.next().?;
    const tv = try rdata_mod.decodeTxt(r_txt);
    try testing.expectEqualStrings("1", tv.get("V").?);
    try testing.expect(tv.has("FLAG"));
    var ar = m.additional();
    try testing.expectEqual([4]u8{ 10, 0, 0, 1 }, try rdata_mod.decodeA(ar.next().?.rdata));
    const got_v6 = try rdata_mod.decodeAaaa(ar.next().?.rdata);
    try testing.expectEqual(v6, got_v6);
    const r_nsec = ar.next().?;
    const nsec = try rdata_mod.decodeNsec(pkt, r_nsec);
    try testing.expect(nsec.next.eql(&host));
    try testing.expect(nsec.has(.a) and nsec.has(.aaaa) and !nsec.has(.srv));
    const h = try rdata_mod.decodeHinfo(ar.next().?);
    try testing.expectEqualStrings("macOS", h.os);
    try testing.expect(ar.next() == null);
}

test "QU and cache-flush bits round trip through the builder" {
    var buf: [512]u8 = undefined;
    var b = Builder.init(&buf, .{});
    const n = try Name.parse("host.local");
    try b.addQuestion(n, .any, message.class_in, true);
    try b.addQuestion(n, .a, message.class_in, false);
    try b.addRR(.answer, n, .a, message.class_in, true, 120, .{ .a = .{ 1, 2, 3, 4 } });
    try b.addRR(.answer, n, .a, message.class_in, false, 120, .{ .a = .{ 1, 2, 3, 5 } });
    const m = try Message.parse(b.finish());
    var qs = m.questions();
    try testing.expect(qs.next().?.qu);
    try testing.expect(!qs.next().?.qu);
    var an = m.answers();
    const r1 = an.next().?;
    try testing.expect(r1.cache_flush);
    try testing.expectEqual(message.class_in, r1.class);
    try testing.expectEqual(@as(u16, 0x8001), r1.class_raw);
    const r2 = an.next().?;
    try testing.expect(!r2.cache_flush);
    try testing.expectEqual(@as(u16, 1), r2.class_raw);
}

test "legacy builder never compresses SRV target" {
    const inst = try Name.parse("Alice._qmsg._udp.local");
    const host = try Name.parse("studio-a.local");
    const srv: Srv = .{ .port = 4433, .target = host };
    const nsec = try Nsec.fromTypes(host, &.{ .a, .srv });

    var flat: [64]u8 = undefined;
    const flat_len = try rdata_mod.encodeSrv(srv, &flat);
    var flat_nsec: [64]u8 = undefined;
    const flat_nsec_len = try rdata_mod.encodeNsec(nsec, &flat_nsec);

    var buf: [512]u8 = undefined;
    for ([_]bool{ false, true }) |legacy| {
        var b = Builder.init(&buf, .{ .legacy = legacy });
        b.setId(0x1234);
        b.setResponse();
        try b.addQuestion(inst, .srv, message.class_in, false);
        // Puts "studio-a.local" in the packet before the SRV so there is
        // something to compress against.
        try b.addRR(.answer, host, .a, message.class_in, true, 120, .{ .a = .{ 10, 0, 0, 1 } });
        try b.addRR(.answer, inst, .srv, message.class_in, true, 120, .{ .srv = srv });
        try b.addRR(.additional, host, .nsec, message.class_in, true, 120, .{ .nsec = nsec });
        const pkt = b.finish();
        const m = try Message.parse(pkt);
        try testing.expectEqual(@as(u16, 0x1234), m.header.id);
        var an = m.answers();
        const r_a = an.next().?;
        const r_srv = an.next().?;
        const decoded = try rdata_mod.decodeSrv(pkt, r_srv);
        try testing.expect(decoded.target.eql(&host));
        try testing.expectEqual(@as(u16, 4433), decoded.port);
        var ar = m.additional();
        const r_nsec = ar.next().?;
        try testing.expect((try rdata_mod.decodeNsec(pkt, r_nsec)).has(.srv));
        if (legacy) {
            try testing.expectEqualSlices(u8, flat[0..flat_len], r_srv.rdata);
            // RFC 4034 section 4.1.1 (via RFC 6762 section 6.7): the NSEC
            // next-domain name is a full uncompressed name in a legacy
            // reply, so the rdata starts with the label, not a pointer.
            try testing.expectEqualSlices(u8, flat_nsec[0..flat_nsec_len], r_nsec.rdata);
            try testing.expectEqual(@as(u8, "studio-a".len), r_nsec.rdata[0]);
            // TTL capped at 10 s and cache-flush cleared (section 6.7).
            try testing.expectEqual(legacy_ttl_cap_s, r_a.ttl);
            try testing.expectEqual(legacy_ttl_cap_s, r_srv.ttl);
            try testing.expect(!r_a.cache_flush and !r_srv.cache_flush);
            // The owner name is still compressed in legacy mode: the SRV
            // record starts right after the A rdata with a 2-octet pointer.
            try testing.expectEqual(r_a.rdata_offset + 4 + 2 + 10, r_srv.rdata_offset);
        } else {
            try testing.expect(r_srv.rdata.len < flat_len);
            // Multicast: the next name is a 2-octet pointer (section 18.14).
            try testing.expectEqual(2 + 2 + nsec.bitmapLen(), r_nsec.rdata.len);
            try testing.expectEqual(@as(u32, 120), r_a.ttl);
            try testing.expect(r_a.cache_flush and r_srv.cache_flush);
        }
    }
}

test "builder writes an empty TXT as a single zero byte" {
    // RFC 6763 section 6.1: "DNS-SD implementations MUST NOT emit empty
    // TXT records." `Txt.fromWire("")` accepts an empty rdata from a peer
    // for interoperability; re-emitting it must still produce one zero
    // octet, the same bytes `Txt.build(&.{})` gives.
    var buf: [256]u8 = undefined;
    var b = Builder.init(&buf, .{});
    const n = try Name.parse("x.local");
    const from_peer = try txt_mod.Txt.fromWire("");
    try testing.expectEqual(@as(usize, 0), from_peer.slice().len);
    try b.addRR(.answer, n, .txt, message.class_in, false, 4500, .{ .txt = from_peer.slice() });
    try b.addRR(.answer, n, .txt, message.class_in, false, 4500, .{ .txt = "" });
    try b.addRR(.answer, n, .txt, message.class_in, false, 4500, .{ .txt = (try txt_mod.Txt.build(&.{})).slice() });
    const pkt = b.finish();
    const m = try Message.parse(pkt);
    var an = m.answers();
    var count: usize = 0;
    while (an.next()) |r| : (count += 1) {
        try testing.expectEqualSlices(u8, "\x00", r.rdata);
        const v = try rdata_mod.decodeTxt(r);
        try testing.expectEqual(@as(usize, 0), v.count());
    }
    try testing.expectEqual(@as(usize, 3), count);
    // Structurally invalid TXT bytes are refused and the builder is
    // unchanged (a length octet running past the rdata).
    const before = b.payloadLen();
    try testing.expectError(error.InvalidTxt, b.addRR(.answer, n, .txt, message.class_in, false, 4500, .{ .txt = "\x05ab" }));
    try testing.expectEqual(before, b.payloadLen());
    try testing.expectEqual(@as(usize, 3), b.recordCount());
    // `.raw` stays verbatim for callers that really want arbitrary bytes.
    try b.addRR(.answer, n, .txt, message.class_in, false, 4500, .{ .raw = "\x05ab" });
    try testing.expectEqual(@as(usize, 4), b.recordCount());
}

test "builder emits one RR when over MTU" {
    var buf: [hard_limit_v4]u8 = undefined;
    const big_txt: [2000]u8 = @splat(0); // 2000 empty strings
    const n = try Name.parse("big.local");
    // First record over the soft target is accepted.
    var b = Builder.init(&buf, .{ .family = .v4 });
    try b.addRR(.answer, n, .txt, message.class_in, false, 4500, .{ .txt = &big_txt });
    try testing.expect(b.payloadLen() > soft_limit_v4);
    try testing.expectEqual(@as(usize, 1), b.recordCount());
    // A second record, however small, does not fit any more.
    const before = b.payloadLen();
    try testing.expectError(error.NoSpace, b.addRR(.answer, n, .a, message.class_in, false, 120, .{ .a = .{ 1, 2, 3, 4 } }));
    try testing.expectEqual(before, b.payloadLen());
    try testing.expectEqual(@as(usize, 1), b.recordCount());
    const m = try Message.parse(b.finish());
    try testing.expectEqual(@as(u16, 1), m.header.ancount);
    // The other order: a small first record, then the oversize one, is
    // refused and leaves the builder unchanged.
    var c = Builder.init(&buf, .{ .family = .v4 });
    try c.addRR(.answer, n, .a, message.class_in, false, 120, .{ .a = .{ 1, 2, 3, 4 } });
    const small_len = c.payloadLen();
    const comp_before = c.comp_len;
    try testing.expectError(error.NoSpace, c.addRR(.answer, n, .txt, message.class_in, false, 4500, .{ .txt = &big_txt }));
    try testing.expectEqual(small_len, c.payloadLen());
    try testing.expectEqual(comp_before, c.comp_len);
    try testing.expectEqual(@as(u16, 1), (try Message.parse(c.finish())).header.ancount);
    // Records that fit under the soft target keep going.
    try c.addRR(.additional, n, .a, message.class_in, false, 120, .{ .a = .{ 1, 2, 3, 5 } });
    try testing.expectEqual(@as(usize, 2), c.recordCount());
}

test "builder payload never exceeds 8972 v4 or 8952 v6" {
    var buf: [9000]u8 = undefined;
    const n = try Name.parse("cap.local");
    const chunk: [1000]u8 = @splat(0);
    const big: [9000]u8 = @splat(0);
    for ([_]Family{ .v4, .v6 }) |family| {
        const cap = hardLimit(family);
        // A single record over the hard cap is refused.
        var b = Builder.init(&buf, .{ .family = family });
        try testing.expectError(error.NoSpace, b.addRR(.answer, n, .txt, message.class_in, false, 1, .{ .txt = &big }));
        try testing.expect(b.isEmpty());
        // A single record that lands exactly on the cap is accepted.
        const exact = cap - Header.len - n.len - 10;
        try b.addRR(.answer, n, .txt, message.class_in, false, 1, .{ .txt = big[0..exact] });
        try testing.expectEqual(cap, b.payloadLen());
        try testing.expectError(error.NoSpace, b.addRR(.answer, n, .a, message.class_in, false, 1, .{ .a = .{ 0, 0, 0, 0 } }));
        _ = try Message.parse(b.finish());
        // One octet more is refused.
        b.reset();
        try testing.expectError(error.NoSpace, b.addRR(.answer, n, .txt, message.class_in, false, 1, .{ .txt = big[0 .. exact + 1] }));
        try testing.expect(b.isEmpty());
        // Filling with mid-size records stops under the soft target.
        var c = Builder.init(&buf, .{ .family = family });
        var added: usize = 0;
        while (true) {
            c.addRR(.answer, n, .txt, message.class_in, false, 1, .{ .txt = &chunk }) catch |err| {
                try testing.expectEqual(error.NoSpace, err);
                break;
            };
            added += 1;
            try testing.expect(c.payloadLen() <= cap);
            try testing.expect(added < 100);
        }
        try testing.expect(c.payloadLen() <= softLimit(family));
        try testing.expectEqual(@as(usize, 1), added);
        const m = try Message.parse(c.finish());
        try testing.expectEqual(@as(u16, 1), m.header.ancount);
        // A smaller buffer lowers the hard cap.
        var small: [100]u8 = undefined;
        var d = Builder.init(&small, .{ .family = family });
        try testing.expectEqual(@as(usize, 100), d.hard_limit);
        try testing.expectEqual(@as(usize, 100), d.soft_limit);
        try testing.expectError(error.NoSpace, d.addRR(.answer, n, .txt, message.class_in, false, 1, .{ .txt = chunk[0..90] }));
        try d.addRR(.answer, n, .txt, message.class_in, false, 1, .{ .txt = chunk[0..67] });
        try testing.expectEqual(@as(usize, 100), d.payloadLen());
        // An `Options.hard_limit` (or `soft_limit`) override can lower the
        // cap but never lift it above the RFC 6762 section 17 payload cap.
        var e = Builder.init(&buf, .{ .family = family, .hard_limit = 9000, .soft_limit = 9000 });
        try testing.expectEqual(cap, e.hard_limit);
        try testing.expectEqual(cap, e.soft_limit);
        try testing.expectError(error.NoSpace, e.addRR(.answer, n, .txt, message.class_in, false, 1, .{ .txt = big[0 .. exact + 1] }));
        try testing.expect(e.isEmpty());
        try e.addRR(.answer, n, .txt, message.class_in, false, 1, .{ .txt = big[0..exact] });
        try testing.expectEqual(cap, e.payloadLen());
        const f = Builder.init(&buf, .{ .family = family, .hard_limit = 600 });
        try testing.expectEqual(@as(usize, 600), f.hard_limit);
    }
}

